using Bepthaymao.Application;
using Bepthaymao.Api.Health;
using Bepthaymao.Api.Errors;
using Bepthaymao.Api.Observability;
using Bepthaymao.Api.OpenApi;
using Bepthaymao.Api.Security;
using Serilog;
using Bepthaymao.Api.Configuration;
using Bepthaymao.Infrastructure;
using Bepthaymao.Api.Endpoints.Branches;
using Bepthaymao.Api.Endpoints.Auth;

if (args.Length > 0 && args[0] == "db") return await Bepthaymao.Api.Cli.DbCommand.RunAsync(args[1..]);
WebApplicationBuilder builder = WebApplication.CreateBuilder(args);
builder.AddApiLogging();
builder.Services.AddApplication();
builder.Services.AddInfrastructure(builder.Configuration);
builder.Services.AddScoped<Bepthaymao.Api.Cli.SeedRunner>();
builder.Services.AddIntegrationModes(builder.Configuration);
builder.Services.AddApiOpenApi();
builder.Services.AddApiHealthChecks(builder.Configuration);
builder.Services.AddApiTelemetry(builder.Configuration);
builder.Services.AddApiErrorHandling();
builder.Services.AddApiForwardedHeaders(builder.Configuration);
builder.Services.AddApiRateLimiting(builder.Configuration);
builder.Services.AddApiAuthentication(builder.Configuration);
WebApplication app = builder.Build();
app.UseForwardedHeaders();
app.UseMiddleware<CorrelationIdMiddleware>();
app.UseSerilogRequestLogging();
app.UseApiErrorHandling();
app.UseRateLimiter();
app.UseAuthentication();
app.UseAuthorization();
app.NewVersionedApi("Bepthaymao").MapGroup("/api/v{version:apiVersion}").HasApiVersion(1.0).MapPublicBranchesEndpoints().MapAuthEndpoints().MapOwnerBranchesEndpoints();
app.MapOpenApi().WithDocumentPerVersion().AllowAnonymous();
app.MapApiHealthEndpoints();
await app.RunAsync();
return 0;
